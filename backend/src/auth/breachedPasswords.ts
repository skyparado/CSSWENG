/** "Password123!" -> ["password123!", "password"] */
function candidates(password: string): string[] {
  const lower = password.toLowerCase();
  const stem = lower.replace(/[^a-z]+$/, '');
  return stem && stem !== lower ? [lower, stem] : [lower];
}

/** True when the password, or its letters-only stem, is a known breached one. */
export function isBreachedPassword(password: string): boolean {
  return candidates(password).some((c) => BREACHED.has(c));
}

export const BREACHED_PASSWORD_COUNT = BREACHED.size;
